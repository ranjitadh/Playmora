export function getGameById(id: string): GameDefinition | undefined {
  return GAME_CATALOG.find((g) => g.id === id);
}

export function getGamesByCategory(category: GameDefinition['category']): GameDefinition[] {
  return GAME_CATALOG.filter((g) => g.category === category);
}

export function getImplementedGames(): GameDefinition[] {
  return GAME_CATALOG.filter((g) => g.isImplemented);
}

/**
 * A game is multiplayer when it supports more than one player.
 * Multiplayer games are surfaced in the dedicated Multiplayer tab.
 */
export function isMultiplayerGame(game: GameDefinition): boolean {
  return (game.maxPlayers ?? 1) > 1;
}

export function getMultiplayerGames(): GameDefinition[] {
  return GAME_CATALOG.filter(isMultiplayerGame);
}

export function getSinglePlayerGames(): GameDefinition[] {
  return GAME_CATALOG.filter((g) => !isMultiplayerGame(g));
}
